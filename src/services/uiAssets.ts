export const UI_ASSET_MAP = new Map<string, UiAsset>(UI_ASSETS.map(asset => [asset.id, asset]));

export function queryUiAssets(category: UiAssetCategory | 'all' = 'all', query = ''): UiAsset[] {
  const normalized = query.trim().toLowerCase();
  const pool = category === 'all' ? UI_ASSETS : UI_ASSETS.filter(asset => asset.category === category);
  if (!normalized) return [...pool];
  const terms = normalized.split(/[\s,，/]+/).filter(Boolean);
  const scored = pool.map(asset => {
    const haystack = `${asset.id} ${asset.category} ${asset.title} ${asset.description} ${asset.tags.join(' ')}`.toLowerCase();
    const score = terms.reduce((total, term) => total + (haystack.includes(term) ? 1 : 0), 0);
    return { asset, score };
  });
  const matched = scored.filter(item => item.score > 0).sort((a, b) => b.score - a.score).map(item => item.asset);
  return matched.length ? matched : [...pool];
}
