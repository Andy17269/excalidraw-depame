import assert from 'node:assert/strict';
import { mkdtemp, mkdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { Acde } from '../scripts/acde-driver.mjs';
import { createNativeFixture, enterCanvas } from '../scripts/native-fixture.mjs';
const output = resolve(process.env.CANVAS_TEST_OUTPUT || '.debug/resize');
await mkdir(output, { recursive: true });
const profile = await mkdtemp(join(output, 'profile-'));
const acde = await Acde.launch({ cwd: await createNativeFixture(profile), out: join(profile, 'build'), headless: true, env: { XDG_DATA_HOME: join(profile, 'data'), XDG_CONFIG_HOME: join(profile, 'config'), XDG_STATE_HOME: join(profile, 'state'), ACDE_STORAGE: '', ACDE_SCALE: '1.5' } });
try {
  const app = acde.window('excalidraw-depame');
  await enterCanvas(app);
  const frame = () => app.evaluate('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
  const scene = async () => JSON.parse(await app.evaluate('window.canvasBridge.read_canvas()'));
  const drag = async (x,y,a,b) => { await app.mouse.move(x,y); await app.mouse.down(); await frame(); await app.mouse.move(a,b,{steps:8}); await app.mouse.up(); await frame(); };
  await app.getByRole('button', {name:'矩形',exact:true}).click({timeout:20000});
  await drag(600,250,800,400);
  await app.getByRole('button', {name:'选择',exact:true}).click();
  await app.screenshot({path:join(output,'before.png')});
  await drag(800,400,950,500);
  await app.screenshot({path:join(output,'after.png')});
  assert.ok((await scene())[0].width > 300, 'Corner handle did not resize rectangle');
  await app.getByRole('textbox',{name:'宽',exact:true}).fill('400');
  await app.keyboard.press('Enter'); await frame();
  assert.equal((await scene())[0].width,400);
  await app.mouse.click(700,320,{button:'right'});
  await frame();
  assert.equal(await app.evaluate('getComputedStyle(document.querySelector(".context-menu")).borderRadius'),'24px');
  assert.equal(await app.evaluate('getComputedStyle(document.querySelector(".context-menu [data-testid=addToLibrary]")).display'),'none');
  await app.screenshot({path:join(output,'menu.png')});
  await app.locator('.context-menu .dangerous').click(); await frame();
  assert.equal((await scene()).length,0,'Styled context menu delete must remain functional');
  await app.getByRole('button',{name:'文字',exact:true}).click(); await frame();
  await app.mouse.move(600,250); await app.mouse.down(); await frame(); await app.mouse.up(); await frame();
  await app.keyboard.insertText('尺寸调整'); await app.keyboard.press('Escape'); await frame();
  const initialWidth=(await scene())[0].width;
  await app.getByRole('button',{name:'字号 36',exact:true}).click(); await frame();
  const large=(await scene())[0].width;
  assert.ok(large>initialWidth*1.5,'Font preset must resize actual text');
  await app.getByRole('textbox',{name:'字号',exact:true}).fill('28');
  await app.keyboard.press('Enter'); await frame();
  assert.ok((await scene())[0].width<large,'Numeric font size must resize actual text');
  await app.keyboard.press('ctrl+z'); await frame();
  assert.ok(Math.abs((await scene())[0].width-large)<1,'Font resize must support undo');
  await app.screenshot({path:join(output,'text-size.png')});
  assert.deepEqual((await acde.console({level:'errors'})).entries,[]);
  console.log('PASS corner resize, numeric width, font sizes, undo and frosted context-menu action');
} catch(error) { console.error(error.message); console.error(acde.logs?.tail(8).text); process.exitCode=1; }
finally { await acde.close(); }
