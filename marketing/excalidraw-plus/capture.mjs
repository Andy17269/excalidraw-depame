import { mkdir, mkdtemp } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { Acde } from '../../scripts/acde-driver.mjs';
import { createNativeFixture } from '../../scripts/native-fixture.mjs';
const output = resolve('marketing/excalidraw-plus/assets');
const base = resolve('.debug/promo'); await mkdir(base,{recursive:true});
const profile=await mkdtemp(join(base,'profile-'));
const acde=await Acde.launch({cwd:await createNativeFixture(profile),out:join(profile,'build'),headless:true,env:{XDG_DATA_HOME:join(profile,'data'),XDG_CONFIG_HOME:join(profile,'config'),XDG_STATE_HOME:join(profile,'state'),ACDE_STORAGE:''}});
const app=acde.window('excalidraw-depame');
const frame=()=>app.evaluate('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
const wait=async code=>{for(let i=0;i<500;i++){if(await app.evaluate(code))return;await frame();}throw Error('Wait: '+code)};
const shot=async name=>{for(let i=0;i<15;i++)await frame();await app.screenshot({path:join(output,name+'.png')});console.log('Captured '+name)};
try{
await acde.resize('excalidraw-depame',1600,1000);
await acde.emulate({colorScheme:'light',reducedMotion:true});
await wait('!!document.querySelector(".welcome-continue") && !document.querySelector(".welcome-continue").disabled');
await app.evaluate('localStorage.setItem("excalidraw-plus.tour-completed","1")');
await app.locator('.welcome-skip').click();
await wait('!document.querySelector(".welcome-screen")');
await acde.reload('excalidraw-depame');
await wait('!!document.querySelector(".startup-action-btn") && !document.querySelector(".startup-action-btn").disabled');
await shot('startup');
await app.locator('.startup-action-btn.is-primary').click();
await wait('!document.querySelector(".welcome-screen")');
await shot('canvas-empty');
await app.evaluate('window.canvasBridge.draw_diagram('+JSON.stringify('flowchart LR\nA[灵感] --> B[梳理想法]\nB --> C[绘制流程]\nB --> D[设计界面]\nC --> E[让创意成形]\nD --> E\nstyle A fill:#e3f2fd,stroke:#2196f3\nstyle E fill:#e3f2fd,stroke:#2196f3')+')');
await shot('diagram');
await acde.emulate({colorScheme:'dark'}); await shot('diagram-dark');
await acde.emulate({colorScheme:'light'});
await acde.reload('excalidraw-depame');
await wait('!!document.querySelector(".startup-action-btn") && !document.querySelector(".startup-action-btn").disabled');
await app.locator('.startup-action-btn.is-primary').click();
await wait('!document.querySelector(".welcome-screen")');
await app.getByRole('button',{name:'预设模板',exact:true}).click();
await app.getByRole('menuitem',{name:'音乐 App',exact:true}).click();
await wait('JSON.parse(window.canvasBridge.read_canvas()).length>8');
await shot('sketch');
await app.getByRole('button',{name:'UI草图',exact:true}).click();
await app.getByRole('button',{name:'整页生成',exact:true}).click();
await wait('JSON.parse(window.canvasBridge.read_canvas()).some(x=>x.type==="text"&&x.text.includes("DAMIDAMI")) && !document.querySelector(".ai-cursor.is-visible")');
await shot('ui');
console.log('Capture complete');
}catch(e){await shot('failure');console.error(e.message);process.exitCode=1}finally{await acde.close()}
